    private void btfinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btfinalizarActionPerformed
        try {
            // CHAMA O CONTROLLER PARA EXECUTAR A TRANSAÇÃO COMPLETA
            controller.finalizarVenda();

            // FEEDBACK DE SUCESSO
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Venda finalizada com sucesso! Pontos foram acumulados.",
                    "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // NAVEGAÇÃO
            btVoltarActionPerformed(evt); // Volta para a tela principal

        } catch (Exception e) {
            // TRATAMENTO DE ERRO DE TRANSAÇÃO (Ex: Venda sem itens)
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Falha ao finalizar venda: " + e.getMessage(),
                    "Erro de Transação", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

        JanelaPrincipalView view = new JanelaPrincipalView();
        view.setVisible(true);
        this.setVisible(false);

    }//GEN-LAST:event_btfinalizarActionPerformed
    private void updateItemsTable() {
        // 1. Limpa todas as linhas atuais da tabela
        tableModel.setRowCount(0);

        // 2. Itera sobre a lista temporária do Controller
        controller.getItensVendaTemp().forEach(item -> {
            // Adiciona uma nova linha com os dados do item
            tableModel.addRow(new Object[]{
                item.getProduto().getNome(),
                item.getQuantidade(),
                item.getSubTotal()
            });
        });
    }

