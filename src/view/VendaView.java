    private void btaddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btaddActionPerformed
        int idcliente = 0;
        int idproduto = 0;
        int quant = 0;

        try {
            // COLETA E CONVERSÃO DOS DADOS
            idcliente = Integer.parseInt(tfidcliente.getText().trim());
            idproduto = Integer.parseInt(tfidproduto.getText().trim());
            quant = Integer.parseInt(tfquant.getText().trim());

            // CHAMA O CONTROLLER (Ele cuida da lógica de cliente e estoque)
            if (controller.getClienteAtual() == null) {
                controller.setClienteVenda(idcliente); // Define o cliente na primeira vez
                tfidcliente.setEditable(false);
            } else if (controller.getClienteAtual().getId() != idcliente) {
                throw new Exception("O ID do cliente não pode ser alterado durante a venda.");
            }

            controller.adicionarItem(idproduto, quant);

            // FEEDBACK E ATUALIZAÇÃO DA TELA
            updateItemsTable();
            tfidproduto.setText("");
            tfquant.setText("");

        } catch (NumberFormatException e) {
            // Erro se digitar letra em ID/Quantidade
            javax.swing.JOptionPane.showMessageDialog(this,
                    "IDs e Quantidade devem ser números válidos.",
                    "Erro de Input", javax.swing.JOptionPane.ERROR_MESSAGE);

        } catch (Exception e) {
            // Erro de lógica (Cliente não existe, Estoque insuficiente, etc.)
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Falha ao adicionar item: " + e.getMessage(),
                    "Erro de Venda", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btaddActionPerformed

