    private void loadClientes() {
        tableModel.setRowCount(0); // Limpa as linhas existentes

        try {
            List<Cliente> clientes = controller.buscarTodosClientes();

            for (Cliente c : clientes) {
                // Adiciona uma linha na tabela para cada cliente encontrado
                tableModel.addRow(new Object[]{
                    c.getId(),
                    c.getNome(),
                    c.getCpf(),
                    c.getTelefone(),
                    c.getTotalPontosAcumulados()
                });
            }
        } catch (Exception ex) {
            // Se houver erro de conexão/SQL, avisa o usuário
            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar lista de clientes: " + ex.getMessage(),
                    "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    public void refreshTable() {
        loadClientes();
    }

