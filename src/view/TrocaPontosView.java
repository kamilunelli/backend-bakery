    private void btsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btsalvarActionPerformed
        try {
            int idcliente = Integer.parseInt(tfidcliente.getText().trim());
            int idproduto = Integer.parseInt(tfidproduto.getText().trim());
            int quant = Integer.parseInt(tfquant.getText().trim());

            troca.trocarPontos(idcliente, idproduto, quant);

            JOptionPane.showMessageDialog(this, "Resgate efetuado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

            JanelaPrincipalView view = new JanelaPrincipalView();
            view.setVisible(true);
            this.setVisible(false);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro de formato: Certifique-se de que ID Cliente, ID Produto e Quantidade são números inteiros.",
                    "Erro de Entrada",
                    JOptionPane.ERROR_MESSAGE);
            logger.log(java.util.logging.Level.WARNING, "Erro de formato de número", e);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao resgatar pontos:\n" + e.getMessage(),
                    "Erro de Resgate",
                    JOptionPane.ERROR_MESSAGE);
            logger.log(java.util.logging.Level.SEVERE, "Erro durante a troca de pontos", e);
        }

    }//GEN-LAST:event_btsalvarActionPerformed

